"""
Задачи для каждой роли AI-команды.
"""

from crewai import Task
from agents import architect, developer, qa_gate, devops


def make_tasks(task_description: str) -> list[Task]:
    """Создать все задачи для команды на основе входящего описания."""

    architecture_doc = Task(
        description=f"""
        Ты получил задачу от пользователя. Спроектируй полное решение.

        ЗАДАЧА ПОЛЬЗОВАТЕЛЯ:
        {task_description}

        Твой документ ДОЛЖЕН содержать (markdown, минимум 500 слов):
        1. **Обзор**: что делает система, ключевые сценарии использования
        2. **Технологический стек**: языки, фреймворки, БД, кэш, очереди — с обоснованием выбора
        3. **Архитектура**: диаграмма компонентов (текстом), описание каждого
        4. **Модель данных**: сущности, поля, связи, индексы
        5. **API-контракты**: endpoints, методы, форматы запросов/ответов, коды ошибок
        6. **Нефункциональные требования**: безопасность, производительность, масштабирование
        7. **Структура проекта**: дерево файлов и папок

        Это — ЕДИНСТВЕННЫЙ источник правды для Разработчика и DevOps.
        Не сжимай информацию в YAML/JSON — пиши полный человекочитаемый текст.
        """,
        expected_output="Полный архитектурный документ в формате Markdown (минимум 500 слов, "
                       "содержит все 7 разделов). Документ самодостаточен — "
                       "Разработчик не должен додумывать.",
        agent=architect,
    )

    coding_task = Task(
        description="""
        Напиши код строго по архитектурному документу, который создал Архитектор.

        ТРЕБОВАНИЯ:
        - Весь код в одном ответе (не по частям)
        - Каждый файл в markdown-блоке с указанием пути: ```python path/to/file.py
        - Включай requirements.txt или pyproject.toml
        - Включай тесты (pytest)
        - Включай .env.example
        - Если в архитектурном документе есть неясности — отметь в комментариях кода

        КАЧЕСТВО:
        - Типизация (type hints) на всех публичных функциях
        - Документирующие комментарии к классам и сложным функциям
        - Обработка ошибок (не голые try/except)
        - Валидация входных данных
        """,
        expected_output="Полная кодовая база: каждый файл в отдельном markdown-блоке "
                       "с указанием пути. Код рабочий, типизированный, "
                       "с тестами и документацией.",
        agent=developer,
    )

    qa_code_task = Task(
        description="""
        Проверь код Разработчика на соответствие архитектурному документу Архитектора.

        ЧТО ПРОВЕРЯТЬ:
        1. **Соответствие архитектуре**: все ли компоненты реализованы? Нет ли лишнего?
        2. **Безопасность**: SQL-инъекции, XSS, утечки секретов, небезопасные зависимости
        3. **Обработка ошибок**: все ли исключения обработаны? Нет ли голых try/except?
        4. **Валидация**: проверяются ли входные данные на всех endpoint-ах?
        5. **Тесты**: есть ли они? Покрывают ли основные сценарии?
        6. **Style guide**: PEP 8, нейминг, типизация

        ФОРМАТ ОТВЕТА:
        Для каждой найденной проблемы:
        - Приоритет: 🔴 (критично — блокирует запуск) / 🟡 (важно — нужно исправить) / 🟢 (минор — можно так)
        - Файл и строка (если применимо)
        - Описание проблемы
        - Предложение по исправлению

        В конце: ИТОГОВЫЙ ВЕРДИКТ — ✅ Go (нет критических проблем) или ❌ No-Go (требуются правки).
        Если No-Go — перечисли КОНКРЕТНЫЕ файлы и строки, которые нужно исправить.
        """,
        expected_output="Отчёт о проверке кода: список проблем с приоритетами, "
                       "конкретные файлы и строки, итоговый вердикт (✅ Go / ❌ No-Go).",
        agent=qa_gate,
    )

    fix_task = Task(
        description="""
        QA Gate нашёл проблемы в твоём коде. Исправь ИСКЛЮЧИТЕЛЬНО то, что указано в отчёте QA.

        ПРАВИЛА:
        - Исправляй только проблемы с приоритетом 🔴 и 🟡
        - 🟢 (минор) — только если есть время и это не меняет архитектуру
        - НЕ переписывай код с нуля — точечные правки
        - После исправления выложи полную кодовую базу заново (все файлы)

        В ответе укажи: что исправлено и почему (одна строка на каждое исправление).
        """,
        expected_output="Исправленная кодовая база (все файлы заново) + список исправлений.",
        agent=developer,
    )

    docker_task = Task(
        description="""
        Упакуй готовое решение в Docker.

        ЧТО СДЕЛАТЬ:
        1. **Dockerfile**: multi-stage build, используй путь `url-shortener/Dockerfile`
        2. **docker-compose.yml**: все сервисы, путь `url-shortener/docker-compose.yml`
        3. **.env.example**: все переменные, путь `url-shortener/.env.example`
        4. **README.md**: как запустить, путь `url-shortener/README.md`
        5. **Healthcheck**: для каждого сервиса

        ПРАВИЛА:
        - Не используй latest-теги — фиксируй версии
        - Не копируй .env в образ
        - Используй не-root пользователя в контейнере
        - Пути файлов ВСЕГДА начинай с `url-shortener/`, не с `path/to/`
        """,
        expected_output="Dockerfile, docker-compose.yml, .env.example, README.md — "
                       "каждый в отдельном markdown-блоке с указанием пути.",
        agent=devops,
    )

    return [architecture_doc, coding_task, qa_code_task, fix_task, docker_task]
