def make_spec_task(task_description: str, enhance: bool = False, existing_code: str = "",
                   memory: str = "") -> Task:
    """Фаза A1: спека как проверяемый контракт.

    Вынесена в отдельную фазу ради гейта G0: пока архитектура, тесты и
    код шли одним kickoff, между ними нельзя было выполнить код, и пробел в
    спеке обнаруживался только как спор теста и кода на два шага позже
    (прогон 20260812_101353: глубина буфера ввода не была определена вовсе).

    Путь к каталогу прогона в промптах не диктуется: это факт окружения
    (AI_TEAM_RUN_DIR), а не строка, которую модель должна скопировать без ошибки.
    """
    if enhance:
        history_block = (
            f"=== ИСТОРИЯ ПРОЕКТА (прошлые прогоны) ===\n"
            f"{memory}\n=== КОНЕЦ ИСТОРИИ ===\n\n"
            if memory else ""
        )
        mode_intro = (
            "Ты ДОРАБАТЫВАЕШЬ существующий проект, а не проектируешь с нуля. "
            "Ниже — история проекта, текущий код и запрос на доработку. "
            "Спроектируй ТОЛЬКО изменения: что поменять в существующем коде "
            "и какое новое поведение появится. Не переписывай всю архитектуру — "
            "опиши дельту. Раздел 8 (ASSERT-NN) — только для нового/изменённого "
            "поведения.\n\n"
            f"{history_block}"
            f"=== ТЕКУЩИЙ КОД ПРОЕКТА ===\n{existing_code}\n=== КОНЕЦ КОДА ===\n\n"
            "ЗАПРОС НА ДОРАБОТКУ:\n"
            f"{task_description}\n"
        )
    else:
        mode_intro = (
            "Ты получил задачу от пользователя. Спроектируй полное решение.\n\n"
            "ЗАДАЧА ПОЛЬЗОВАТЕЛЯ:\n"
            f"{task_description}\n"
        )
    return Task(
        description=f"""\
        {mode_intro}
        Твой документ ДОЛЖЕН содержать (markdown, минимум 500 слов):
        1. **Обзор**: что делает система, ключевые сценарии использования
        2. **Технологический стек**: языки, фреймворки, БД, кэш, очереди — с обоснованием выбора
        3. **Архитектура**: диаграмма компонентов (текстом), описание каждого
        4. **Модель данных**: сущности, поля, связи, индексы
        5. **API-контракты**: endpoints, методы, форматы запросов/ответов, коды ошибок
        6. **Нефункциональные требования**: безопасность, производительность, масштабирование
        7. **Структура проекта**: дерево файлов и папок
        8. **Проверяемые утверждения** — обязательный раздел, минимум 8 пунктов

        ФОРМАТ РАЗДЕЛА 8 — строго по шаблону, каждый пункт с новой строки:
        ASSERT-01 [P0]: система ДОЛЖНА <наблюдаемое поведение> при <условие>
        ASSERT-02 [P1]: ...
        Номера двузначные, подряд, без пропусков и повторов.
        Приоритет в квадратных скобках сразу после номера:
        - [P0] — критично: безопасность, маскирование данных, целостность,
          контракт API/интеграции, утечки. Падение P0 блокирует деплой.
        - [P1] — основная функциональность: штатный путь пользователя,
          ключевые поля ответа.
        - [P2] — желательно: edge-кейсы, косметика. Падение P2 не блокирует.
        Минимум 2 утверждения [P0]: безопасность/маскирование/контракт — всегда P0.

        Если у системы есть пользовательский интерфейс (веб-фронтенд) — ОБЯЗАТЕЛЬНО:
        - раздел 7 (Структура проекта) явно перечисляет статический фронтенд
          (static/index.html + static/app.js);
        - раздел 8 содержит ASSERT про рабочий JavaScript: «фронт содержит app.js,
          который загружает данные через fetch с API и обрабатывает клики по кнопкам».
          Статический HTML без JS визуально есть, но не работает — это P0-провал.

        Правила формулировки утверждений — по ним пишутся тесты, и споры
        теста с кодом решаются ссылкой на них:
        - утверждение говорит о наблюдаемом извне поведении и никогда о
          деталях внутреннего представления (имена переменных, порядок
          вызовов, точная разметка HTML);
        - если точная строка или формат вывода действительно часть контракта,
          зафиксируй её в утверждении дословно — только так тест вправе
          сравнивать строки буквально;
        - для CLI обязательны утверждения о кодах возврата и потоках вывода;
        - для HTTP API — о кодах ответа и полях тела;
        - для рендеринга — о семантике вывода (какой тег с каким текстом),
          а не о точной разметке;
        - граничные случаи и ошибки — тоже утверждения, не пробелы;
        - если у системы есть состояние, буферы или очереди, явно зафиксируй
          их границы числом: молчание здесь стоило целого прогона.

        Это — ЕДИНСТВЕННЫЙ источник правды для Разработчика и DevOps.
        Не сжимай информацию в YAML/JSON — пиши полный человекочитаемый текст.
        """,
        expected_output="Полный архитектурный документ в формате Markdown (минимум 500 слов, "
                       "все 8 разделов, в восьмом — не менее 8 строк ASSERT-NN). "
                       "Документ самодостаточен — Разработчик не должен додумывать.",
        agent=architect,
        name="architecture",
    )


def make_design_task(spec: str, enhance: bool = False, existing_code: str = "") -> Task:
    """Фаза A1d: UX/UI дизайнер проектирует интерфейс по спеке.

    Между архитектурой (A1) и тестами/кодом (A2): дизайнер выдаёт дизайн-систему
    (styles.css) и мокап структуры (index.html), чтобы Разработчик собирал фронт
    по готовому визуалу, а не рисовал его «на глаз» (как в прогонах до этого).
    """
    enhance_note = (
        "ВАЖНО — ДОРАБОТКА СУЩЕСТВУЮЩЕГО ПРОЕКТА:\n"
        "Ниже — текущий фронт. Проектируй ТОЛЬКО дельту (что добавить/поменять "
        "в UI под запрос), не переписывай весь дизайн с нуля.\n"
        f"=== ТЕКУЩИЙ КОД (фронт) ===\n{existing_code}\n=== КОНЕЦ КОДА ===\n\n"
    ) if enhance else ""
    return Task(
        description=f"""
        Ты получил архитектурный документ (спеку). Спроектируй ИНТЕРФЕЙС.

        {enhance_note}=== СПЕКА ===
        {spec[:12000]}
        === КОНЕЦ СПЕКИ ===

        Сначала определи, есть ли у системы фронтенд:
        - если это ЧИСТЫЙ API без UI — верни один файл design.md со строкой
          «UI не требуется», и НЕ создавай static/.

        ЕСЛИ ФРОНТЕНД ЕСТЬ — верни JSON files с тремя файлами:
        1. design.md — структура UI: страницы, блоки, компоненты, дизайн-токены
           (палитра, шрифты, отступы, радиусы), взаимодействия и состояния
           (hover/active/loading/empty/error).
        2. static/css/styles.css — готовая дизайн-система: CSS-переменные (:root),
           базовые стили, стили компонентов. Без внешних CDN.
        3. static/index.html — мокап структуры: разметка блоков и контролов
           с id/классами (например id="quality-selector"), БЕЗ JS-логики —
           скрипты навесит Разработчик.

        ПРАВИЛА:
        - Только статика (design.md + static/**). НЕ трогай backend/ и tests/.
        - Вёрстка без внешних зависимостей (никаких CDN/фреймворков).
        - Каждый интерактивный контрол помечай id или классом, чтобы Test Designer
          написал на него тест, а Разработчик — навесил логику, не меняя разметку.
        - Соблюдай дизайн-токены из спеки, если заданы; иначе предложи свои.
        - Не пиши JS-логику и не делай запросы к API — это работа Разработчика.
        """,
        expected_output="JSON files: design.md (+ static/css/styles.css и static/index.html, если есть UI).",
        agent=ux_designer,
        output_pydantic=CodeOutput,
        name="design",
    )


