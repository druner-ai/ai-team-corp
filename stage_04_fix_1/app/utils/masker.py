"""ASSERT-01: маскирование — первые 4 + звёздочки + последние 4 символа.

Исправлено: количество звёздочек должно быть равно длине строки минус 8 (первые 4 + последние 4).
Ранее использовалось фиксированное количество звёздочек (8 для карт, 16 для IBAN), что не работало
для строк переменной длины (например, расчётный счёт с разделителем '|').
Теперь вычисляется динамически: len(value) - 8.
"""


class Masker:
    @staticmethod
    def mask(value: str) -> str:
        """Маскирует строку: первые 4 + звёздочки + последние 4.

        Если длина строки < 8, возвращает как есть.
        """
        if len(value) < 8:
            return value
        stars_count = len(value) - 8
        return value[:4] + "*" * stars_count + value[-4:]
